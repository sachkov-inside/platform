import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const destination = new URL("infra/identity/logto/fork/packages/core/src/routes/inside-telegram-theme.ts", root);

export async function generateTelegramSignInTheme() {
  const source = await readFile(new URL("apps/web/app/globals.css", root), "utf8");
  const lightTokens = source.match(/:root\s*\{([^}]+)\}/u)?.[1];
  if (!lightTokens) throw new Error("Platform light tokens are missing");
  const names = ["background", "foreground", "card", "primary", "primary-foreground", "secondary", "muted-foreground", "border", "ring", "elevation-card"];
  const tokens = names.map((name) => {
    const value = lightTokens.match(new RegExp(`--${name}:\\s*([^;]+);`, "u"))?.[1];
    if (!value) throw new Error(`Platform token ${name} is missing`);
    return `  --${name}: ${value};`;
  }).join("\n");
  // Keep the identity origin self-contained; never fetch fonts from a third party.
  const fonts = await Promise.all(["latin", "cyrillic"].map(async (subset) => {
    const font = await readFile(new URL(`apps/web/node_modules/@fontsource-variable/manrope/files/manrope-${subset}-wght-normal.woff2`, root));
    return `@font-face{font-family:Inside Manrope;font-style:normal;font-weight:200 800;font-display:swap;src:url(data:font/woff2;base64,${font.toString("base64")}) format('woff2');unicode-range:${subset === "latin" ? "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD" : "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116"}}`;
  }));
  return `// Generated by scripts/telegram-sign-in-theme.mjs from Platform light tokens and pinned Manrope.\nexport const telegramSignInTheme = ${JSON.stringify(`.inside-telegram {\n${tokens}\n}\n${fonts.join("\n")}`)};\n`;
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], "file:").href) {
  const generated = await generateTelegramSignInTheme();
  if (process.argv.includes("--check")) {
    if (await readFile(destination, "utf8") !== generated) throw new Error("Telegram theme drift: run node scripts/telegram-sign-in-theme.mjs");
  } else await writeFile(destination, generated);
}
