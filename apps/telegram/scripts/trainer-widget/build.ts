import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

import { transform } from "esbuild";

import {
  TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES,
  TELEGRAM_WIDGET_HTML_MAX_BYTES,
  TRAINER_WIDGET_COMPRESSED_BUDGET_BYTES,
} from "../../src/modules/trainer/widget/trainer-widget-limits.js";

// Builds the HTML that sendWidget carries from the widget source inside the application.
// The bot ships the checked-in result: Telegram fixes the code of a widget when it is sent,
// and the production image has no build step for it.
const widgetDirectory = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../src/modules/trainer/widget",
);
const generatedFile = path.join(
  widgetDirectory,
  "trainer-widget-html.generated.ts",
);

export interface TrainerWidgetSize {
  readonly htmlBytes: number;
  /** zlib level 9 as Node.js counts it; Telegram's own count can differ by a few dozen bytes. */
  readonly compressedBytes: number;
}

export async function buildTrainerWidgetHtml(): Promise<string> {
  const [styles, script] = await Promise.all([
    readFile(path.join(widgetDirectory, "widget.css"), "utf8"),
    readFile(path.join(widgetDirectory, "widget.js"), "utf8"),
  ]);
  const [css, js] = await Promise.all([
    transform(styles, { loader: "css", minify: true }),
    transform(script, {
      loader: "js",
      minify: true,
      target: "es2023",
      charset: "utf8",
    }),
  ]);
  return `<style>${css.code.trim()}</style><div id=w></div><script>${js.code.trim()}</script>`;
}

export function trainerWidgetSize(html: string): TrainerWidgetSize {
  const bytes = Buffer.from(html, "utf8");
  return {
    htmlBytes: bytes.byteLength,
    compressedBytes: deflateSync(bytes, { level: 9 }).byteLength,
  };
}

async function writeGeneratedModule(): Promise<void> {
  const html = await buildTrainerWidgetHtml();
  const size = trainerWidgetSize(html);
  if (
    size.htmlBytes > TELEGRAM_WIDGET_HTML_MAX_BYTES ||
    size.compressedBytes > TRAINER_WIDGET_COMPRESSED_BUDGET_BYTES
  )
    throw new Error(
      `Trainer widget is too large: ${String(size.htmlBytes)} bytes of HTML (limit ${String(TELEGRAM_WIDGET_HTML_MAX_BYTES)}), ` +
        `${String(size.compressedBytes)} bytes after zlib level 9 (budget ${String(TRAINER_WIDGET_COMPRESSED_BUDGET_BYTES)}, ` +
        `Telegram limit ${String(TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES)}).`,
    );
  await writeFile(
    generatedFile,
    "// Generated by `pnpm --filter @inside/telegram trainer:widget:build` from widget.css and widget.js.\n" +
      "// Do not edit: change the source and build again.\n" +
      `export const TRAINER_WIDGET_HTML =\n  ${JSON.stringify(html)};\n`,
  );
  const exact = telegramCompressedBytes(html);
  process.stdout.write(
    `Trainer widget: ${String(size.htmlBytes)} bytes of HTML, ${String(size.compressedBytes)} bytes after zlib level 9 as Node.js counts, ` +
      `${String(TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES - size.compressedBytes)} bytes below the Telegram limit.\n` +
      (exact === undefined
        ? "python3 is not available: the count Telegram uses was not taken.\n"
        : `As Telegram counts (Python zlib): ${String(exact)} bytes, ${String(TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES - exact)} below the limit.\n`),
  );
}

/** The guide: "Python's zlib counts exactly as the server does". Undefined without python3. */
function telegramCompressedBytes(html: string): number | undefined {
  try {
    const output = execFileSync(
      "python3",
      [
        "-I",
        "-c",
        "import sys,zlib; print(len(zlib.compress(sys.stdin.buffer.read(), 9)))",
      ],
      { input: html, encoding: "utf8", timeout: 10_000 },
    );
    const bytes = Number(output.trim());
    return Number.isInteger(bytes) ? bytes : undefined;
  } catch {
    return undefined;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  await writeGeneratedModule();
