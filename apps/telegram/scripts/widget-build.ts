import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { deflateSync } from "node:zlib";

import { transform } from "esbuild";

import {
  TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES,
  TELEGRAM_WIDGET_HTML_MAX_BYTES,
} from "../src/modules/outbound/telegram-widget-limits.js";

// Builds the HTML that sendWidget carries from a widget source inside the application.
// The bot ships the checked-in result: Telegram fixes the code of a widget when it is sent,
// and the production image has no build step for it.

/** A widget the bot sends: its source directory, generated module and build command. */
export interface WidgetSource {
  /** How the build output names the widget, such as "Trainer widget". */
  readonly name: string;
  /** Holds widget.css and widget.js. */
  readonly directory: string;
  /** The generated module, inside the directory. */
  readonly generatedFile: string;
  /** The constant the generated module exports. */
  readonly exportName: string;
  /** The package script that rebuilds the generated module. */
  readonly command: string;
}

export interface WidgetSize {
  readonly htmlBytes: number;
  /** zlib level 9 as Node.js counts it; Telegram's own count can differ by a few dozen bytes. */
  readonly compressedBytes: number;
}

export async function buildWidgetHtml(directory: string): Promise<string> {
  const [styles, script] = await Promise.all([
    readFile(path.join(directory, "widget.css"), "utf8"),
    readFile(path.join(directory, "widget.js"), "utf8"),
  ]);
  const [css, js] = await Promise.all([
    transform(styles, { loader: "css", minify: true }),
    transform(script, {
      loader: "js",
      minify: true,
      target: "es2023",
      charset: "utf8",
    }),
  ]);
  return `<style>${css.code.trim()}</style><div id=w></div><script>${js.code.trim()}</script>`;
}

export function widgetSize(html: string): WidgetSize {
  const bytes = Buffer.from(html, "utf8");
  return {
    htmlBytes: bytes.byteLength,
    compressedBytes: deflateSync(bytes, { level: 9 }).byteLength,
  };
}

/** Builds the widget, stops above Telegram's limits and writes its generated module. */
export async function writeWidgetModule(widget: WidgetSource): Promise<void> {
  const html = await buildWidgetHtml(widget.directory);
  const size = widgetSize(html);
  if (
    size.htmlBytes > TELEGRAM_WIDGET_HTML_MAX_BYTES ||
    size.compressedBytes > TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES
  )
    throw new Error(
      `${widget.name} is too large: ${String(size.htmlBytes)} bytes of HTML (limit ${String(TELEGRAM_WIDGET_HTML_MAX_BYTES)}), ` +
        `${String(size.compressedBytes)} bytes after zlib level 9 as Node.js counts ` +
        `(Telegram limit ${String(TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES)}).`,
    );
  await writeFile(
    widget.generatedFile,
    `// Generated by \`pnpm --filter @inside/telegram ${widget.command}\` from widget.css and widget.js.\n` +
      "// Do not edit: change the source and build again.\n" +
      `export const ${widget.exportName} =\n  ${JSON.stringify(html)};\n`,
  );
  const exact = telegramCompressedBytes(html);
  process.stdout.write(
    `${widget.name}: ${String(size.htmlBytes)} bytes of HTML, ${String(size.compressedBytes)} bytes after zlib level 9 as Node.js counts, ` +
      `${String(TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES - size.compressedBytes)} bytes below the Telegram limit.\n` +
      (exact === undefined
        ? "python3 is not available: the count Telegram uses was not taken.\n"
        : `As Telegram counts (Python zlib): ${String(exact)} bytes, ${String(TELEGRAM_WIDGET_COMPRESSED_MAX_BYTES - exact)} below the limit.\n`),
  );
}

/** The guide: "Python's zlib counts exactly as the server does". Undefined without python3. */
function telegramCompressedBytes(html: string): number | undefined {
  try {
    const output = execFileSync(
      "python3",
      [
        "-I",
        "-c",
        "import sys,zlib; print(len(zlib.compress(sys.stdin.buffer.read(), 9)))",
      ],
      { input: html, encoding: "utf8", timeout: 10_000 },
    );
    const bytes = Number(output.trim());
    return Number.isInteger(bytes) ? bytes : undefined;
  } catch {
    return undefined;
  }
}
