import { readFile, writeFile } from "node:fs/promises";

// This generator covers the vocabulary of the pinned provider schema. Unknown
// keywords fail generation so a provider upgrade cannot silently weaken validation.
const root = new URL("../src/modules/communications/", import.meta.url);
const schema = JSON.parse(await readFile(new URL("contracts/inside-communications-v1/schema.json", root), "utf8"));
const definitions = schema.definitions;
const emitted = new Set();
const lines = ['// Generated by scripts/generate-communications-contract.mjs. Do not edit.', 'import { z } from "zod";', ''];
const known = new Set(["type", "format", "enum", "$ref", "oneOf", "additionalProperties", "properties", "required", "items", "minItems", "maxItems", "minLength", "maxLength", "minimum", "maximum", "pattern", "allOf"]);
function emit(name) {
  if (emitted.has(name)) return;
  const expression = convert(definitions[name]);
  lines.push(`export const ${name}Schema = ${expression};`, "");
  emitted.add(name);
}
function convert(value) {
  for (const key of Object.keys(value)) if (!known.has(key)) throw new Error(`Unsupported keyword: ${key}`);
  if (value.allOf) {
    // The provider content contract uses conditionals on its finite media type.
    const { allOf, ...base } = value;
    const variants = base.properties.type.enum.map(type => {
      const variant = structuredClone(base);
      variant.properties.type = { enum: [type] };
      for (const rule of allOf) {
        if (Object.keys(rule).some(key => !["if", "then", "else"].includes(key)) ||
          Object.keys(rule.if).join() !== "properties" ||
          Object.keys(rule.if.properties.type).join() !== "const") throw new Error("Unsupported conditional shape");
        if (Object.keys(rule.if.properties).join() !== "type" || !rule.if.properties.type.const) throw new Error("Unsupported conditional");
        const branch = rule.if.properties.type.const === type ? rule.then : rule.else;
        if (!branch) continue;
        if (Object.keys(branch).some(key => !["required", "properties"].includes(key))) throw new Error("Unsupported conditional branch");
        variant.required = [...new Set([...variant.required, ...(branch.required ?? [])])];
        for (const [key, constraint] of Object.entries(branch.properties ?? {})) {
          if (constraint === false) delete variant.properties[key];
          else variant.properties[key] = { ...variant.properties[key], ...constraint };
        }
      }
      return convert(variant);
    });
    return `z.union([${variants.join(",\n")}])`;
  }
  if (value.$ref) {
    const name = value.$ref.replace("#/definitions/", "");
    if (!definitions[name]) throw new Error(`Unknown reference: ${value.$ref}`);
    emit(name);
    return `${name}Schema`;
  }
  if (value.oneOf) return `z.union([\n${value.oneOf.map(convert).join(",\n")}\n])`;
  if (value.enum) return value.enum.length === 1 ? `z.literal(${JSON.stringify(value.enum[0])})` : `z.enum(${JSON.stringify(value.enum)})`;
  if (Array.isArray(value.type)) return `z.union([${value.type.map(type => convert({ ...value, type })).join(", ")}])`;
  let result;
  switch (value.type) {
    case "object":
      if (value.additionalProperties !== false) throw new Error("Expected closed object");
      return `z.strictObject({\n${Object.entries(value.properties).map(([key, child]) => `  ${JSON.stringify(key)}: ${convert(child)}${value.required.includes(key) ? "" : ".optional()"},`).join("\n")}\n})`;
    case "array": result = `z.array(${convert(value.items)})`; break;
    case "integer": result = "z.number().int()"; break;
    case "boolean": return "z.boolean()";
    case "null": return "z.null()";
    case "string":
      if (value.format && !["uuid", "uri", "date-time"].includes(value.format)) throw new Error(`Unsupported format: ${value.format}`);
      result = value.format === "uuid" ? "z.guid()" : value.format === "uri" ? "z.url()" : value.format === "date-time" ? "z.iso.datetime({ offset: true })" : "z.string()";
      break;
    default: throw new Error(`Unsupported type: ${value.type}`);
  }
  for (const key of ["minimum", "minLength", "minItems"]) if (value[key] !== undefined) result += `.min(${value[key]})`;
  for (const key of ["maximum", "maxLength", "maxItems"]) if (value[key] !== undefined) result += `.max(${value[key]})`;
  if (value.pattern) result += `.regex(new RegExp(${JSON.stringify(value.pattern)}))`;
  return result;
}
Object.keys(definitions).forEach(emit);
const output = `${lines.join("\n").trimEnd()}\n`;
const target = new URL("communications-schema.generated.ts", root);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("Communications schema drift: run pnpm communications:generate");
} else await writeFile(target, output);
