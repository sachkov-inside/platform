// @ts-check
import { readFile, writeFile } from "node:fs/promises";
import { z } from "zod";

/**
 * The part of JSON Schema the provider contract uses. Unknown keywords pass through the check below
 * so that `convert` can name them.
 *
 * @typedef {object} SchemaNode
 * @property {string | string[] | undefined} [type]
 * @property {string | undefined} [format]
 * @property {unknown[] | undefined} [enum]
 * @property {string | undefined} [$ref]
 * @property {SchemaNode[] | undefined} [oneOf]
 * @property {boolean | undefined} [additionalProperties]
 * @property {Record<string, SchemaNode> | undefined} [properties]
 * @property {string[] | undefined} [required]
 * @property {SchemaNode | undefined} [items]
 * @property {number | undefined} [minItems]
 * @property {number | undefined} [maxItems]
 * @property {number | undefined} [minLength]
 * @property {number | undefined} [maxLength]
 * @property {number | undefined} [minimum]
 * @property {number | undefined} [maximum]
 * @property {string | undefined} [pattern]
 * @property {Conditional[] | undefined} [allOf]
 * @typedef {{
 *   required?: string[] | undefined;
 *   properties?: Record<string, SchemaNode | false> | undefined;
 * }} ConditionalBranch
 * @typedef {{
 *   if: { properties: { type: { const: string } } };
 *   then?: ConditionalBranch | undefined;
 *   else?: ConditionalBranch | undefined;
 * }} Conditional
 */

/** @type {z.ZodType<SchemaNode>} */
const schemaNode = z.lazy(() =>
  z
    .object({
      type: z.union([z.string(), z.array(z.string())]).optional(),
      format: z.string().optional(),
      enum: z.array(z.unknown()).optional(),
      $ref: z.string().optional(),
      oneOf: z.array(schemaNode).optional(),
      additionalProperties: z.boolean().optional(),
      properties: z.record(z.string(), schemaNode).optional(),
      required: z.array(z.string()).optional(),
      items: schemaNode.optional(),
      minItems: z.number().optional(),
      maxItems: z.number().optional(),
      minLength: z.number().optional(),
      maxLength: z.number().optional(),
      minimum: z.number().optional(),
      maximum: z.number().optional(),
      pattern: z.string().optional(),
      allOf: z.array(conditional).optional(),
    })
    .passthrough(),
);
const conditionalBranch = z
  .object({
    required: z.array(z.string()).optional(),
    properties: z
      .record(z.string(), z.union([schemaNode, z.literal(false)]))
      .optional(),
  })
  .passthrough();
const conditional = z
  .object({
    if: z
      .object({
        properties: z
          .object({ type: z.object({ const: z.string() }).passthrough() })
          .passthrough(),
      })
      .passthrough(),
    then: conditionalBranch.optional(),
    else: conditionalBranch.optional(),
  })
  .passthrough();

// This generator covers the vocabulary of the shared provider schema. Unknown
// keywords fail generation so a provider upgrade cannot silently weaken validation.
const root = new URL("../src/modules/communications/", import.meta.url);
const schema = z
  .object({ definitions: z.record(z.string(), schemaNode) })
  .passthrough()
  .parse(
    JSON.parse(
      await readFile(
        new URL(
          "../../../docs/contracts/inside-communications-v1/schema.json",
          import.meta.url,
        ),
        "utf8",
      ),
    ),
  );
const definitions = schema.definitions;
/** @type {Set<string>} */
const emitted = new Set();
const lines = [
  "// Generated by scripts/generate-communications-contract.mjs. Do not edit.",
  'import { z } from "zod";',
  "",
];
const known = new Set([
  "type",
  "format",
  "enum",
  "$ref",
  "oneOf",
  "additionalProperties",
  "properties",
  "required",
  "items",
  "minItems",
  "maxItems",
  "minLength",
  "maxLength",
  "minimum",
  "maximum",
  "pattern",
  "allOf",
]);
/** @param {string} name */
function emit(name) {
  if (emitted.has(name)) return;
  const definition = definitions[name];
  if (definition === undefined) throw new Error(`Unknown definition: ${name}`);
  const expression = convert(definition);
  lines.push(`export const ${name}Schema = ${expression};`, "");
  emitted.add(name);
}
/**
 * @param {SchemaNode} value
 * @returns {string}
 */
function convert(value) {
  for (const key of Object.keys(value))
    if (!known.has(key)) throw new Error(`Unsupported keyword: ${key}`);
  if (value.allOf) {
    // The provider content contract uses conditionals on its finite media type.
    const { allOf, ...base } = value;
    const types = base.properties?.["type"]?.enum;
    if (types === undefined)
      throw new Error("Conditional schema needs a type enum");
    const variants = types.map((type) => {
      const variant = structuredClone(base);
      const { properties } = variant;
      // A conditional refines the closed object it belongs to, so both describe it.
      if (properties === undefined || variant.required === undefined)
        throw new Error("Unsupported conditional shape");
      let required = variant.required;
      properties["type"] = { enum: [type] };
      for (const rule of allOf) {
        if (
          Object.keys(rule).some(
            (key) => !["if", "then", "else"].includes(key),
          ) ||
          Object.keys(rule.if).join() !== "properties" ||
          Object.keys(rule.if.properties.type).join() !== "const"
        )
          throw new Error("Unsupported conditional shape");
        if (
          Object.keys(rule.if.properties).join() !== "type" ||
          !rule.if.properties.type.const
        )
          throw new Error("Unsupported conditional");
        const branch =
          rule.if.properties.type.const === type ? rule.then : rule.else;
        if (!branch) continue;
        if (
          Object.keys(branch).some(
            (key) => !["required", "properties"].includes(key),
          )
        )
          throw new Error("Unsupported conditional branch");
        required = [...new Set([...required, ...(branch.required ?? [])])];
        variant.required = required;
        for (const [key, constraint] of Object.entries(
          branch.properties ?? {},
        )) {
          if (constraint === false) delete properties[key];
          else
            properties[key] = {
              ...properties[key],
              ...constraint,
            };
        }
      }
      return convert(variant);
    });
    return `z.union([${variants.join(",\n")}])`;
  }
  if (value.$ref) {
    const name = value.$ref.replace("#/definitions/", "");
    if (!definitions[name]) throw new Error(`Unknown reference: ${value.$ref}`);
    emit(name);
    return `${name}Schema`;
  }
  if (value.oneOf)
    return `z.union([\n${value.oneOf.map((item) => convert(item)).join(",\n")}\n])`;
  if (value.enum)
    return value.enum.length === 1
      ? `z.literal(${JSON.stringify(value.enum[0])})`
      : `z.enum(${JSON.stringify(value.enum)})`;
  if (Array.isArray(value.type))
    return `z.union([${value.type.map((type) => convert({ ...value, type })).join(", ")}])`;
  let result;
  switch (value.type) {
    case "object": {
      if (value.additionalProperties !== false)
        throw new Error("Expected closed object");
      if (value.properties === undefined || value.required === undefined)
        throw new Error("Expected properties and required");
      const { required } = value;
      return `z.strictObject({\n${Object.entries(value.properties)
        .map(
          ([key, child]) =>
            `  ${JSON.stringify(key)}: ${convert(child)}${required.includes(key) ? "" : ".optional()"},`,
        )
        .join("\n")}\n})`;
    }
    case "array":
      if (value.items === undefined) throw new Error("Array needs items");
      result = `z.array(${convert(value.items)})`;
      break;
    case "integer":
      result = "z.number().int()";
      break;
    case "boolean":
      return "z.boolean()";
    case "null":
      return "z.null()";
    case "string":
      if (value.format && !["uuid", "uri", "date-time"].includes(value.format))
        throw new Error(`Unsupported format: ${value.format}`);
      result =
        value.format === "uuid"
          ? "z.guid()"
          : value.format === "uri"
            ? "z.url()"
            : value.format === "date-time"
              ? "z.iso.datetime({ offset: true })"
              : "z.string()";
      break;
    default:
      throw new Error(`Unsupported type: ${value.type}`);
  }
  for (const key of /** @type {const} */ (["minimum", "minLength", "minItems"]))
    if (value[key] !== undefined) result += `.min(${value[key]})`;
  for (const key of /** @type {const} */ (["maximum", "maxLength", "maxItems"]))
    if (value[key] !== undefined) result += `.max(${value[key]})`;
  if (value.pattern)
    result += `.regex(new RegExp(${JSON.stringify(value.pattern)}))`;
  return result;
}
Object.keys(definitions).forEach(emit);
const output = `${lines.join("\n").trimEnd()}\n`;
const target = new URL("communications-schema.generated.ts", root);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "Communications schema drift: run pnpm communications:generate",
    );
} else await writeFile(target, output);
