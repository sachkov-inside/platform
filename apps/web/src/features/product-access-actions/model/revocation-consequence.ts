/**
 * Последствие отзыва словами спецификации #1721. Закроется ли группа, решает сервер в
 * предпросмотре (`community`); экран только называет его ответ и ничего не считает сам.
 */
export function revocationConsequence(
  community: "closes" | "remains",
): readonly string[] {
  return [
    "Материалы продукта закроются.",
    community === "closes"
      ? "Группа в Telegram закроется: у человека не останется другого продукта с группой."
      : "Группа в Telegram останется: её даёт другой продукт человека.",
    "Остальные продукты, история, оплаты и учебные записи сохранятся.",
  ];
}
